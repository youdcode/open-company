#!/usr/bin/env node
// Generates the per-tool files from the single source of truth:
//   roles/*.md             -> .claude/agents/*.md, .codex/agents/*.toml, .opencode/agents/*.md, .agents/agents/*.md
//   .agents/skills/<name>/ -> .claude/skills/<name>/  (Codex, OpenCode and Antigravity read .agents/skills directly)
// Run after editing a role or a skill: npm run sync
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, readText, parseFrontMatter, isMain, helpIfAsked } from './lib/common.mjs';

const NOTE = 'GENERATED by tools/sync-adapters.mjs from roles/{name}.md. Edit the source, then run: npm run sync';
const CLAUDE_MODEL = { light: 'haiku', standard: 'sonnet', strong: 'inherit' };
const FOOTER = `
## Always
- Follow the rules and the protocol in AGENTS.md (sources, nothing sent, write only in workspace/).
- Log your start and end with \`node tools/log.mjs <your role> "..."\`, and finish with a handoff.
- Run tools with the relative path from the project root (\`node tools/x.mjs\`, never an absolute path),
  one command per call: other forms stop to ask the human for permission.
- Return at most 10 lines to the Director, plus the paths of the files you wrote.
`;

function write(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}

function clean(dir, ext) {
  if (!fs.existsSync(dir)) return;
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (f.endsWith(ext) && readText(p).includes('GENERATED by tools/sync-adapters.mjs')) fs.unlinkSync(p);
  }
}

const yamlStr = s => JSON.stringify(String(s));

export function sync() {
  const rolesDir = path.join(ROOT, 'roles');
  const roles = fs.readdirSync(rolesDir).filter(f => f.endsWith('.md')).map(f => {
    const { data, body } = parseFrontMatter(readText(path.join(rolesDir, f)));
    return { ...data, name: data.name || f.slice(0, -3), body: body.trim() + '\n' + FOOTER };
  }).filter(r => r.name !== 'director');

  const out = {
    claude: path.join(ROOT, '.claude', 'agents'),
    codex: path.join(ROOT, '.codex', 'agents'),
    opencode: path.join(ROOT, '.opencode', 'agents'),
    agy: path.join(ROOT, '.agents', 'agents'),
  };
  clean(out.claude, '.md'); clean(out.codex, '.toml'); clean(out.opencode, '.md'); clean(out.agy, '.md');

  for (const r of roles) {
    const note = NOTE.replace('{name}', r.name);
    write(path.join(out.claude, `${r.name}.md`),
      `---\nname: ${r.name}\ndescription: ${yamlStr(r.description)}\nmodel: ${CLAUDE_MODEL[r.tier] || 'inherit'}\n---\n<!-- ${note} -->\n\n${r.body}`);
    if (r.body.includes("'''")) throw new Error(`roles/${r.name}.md contains ''' which breaks TOML`);
    write(path.join(out.codex, `${r.name}.toml`),
      `# ${note}\nname = ${JSON.stringify(r.name)}\ndescription = ${JSON.stringify(r.description)}\ndeveloper_instructions = '''\n${r.body}'''\n`);
    write(path.join(out.opencode, `${r.name}.md`),
      `---\ndescription: ${yamlStr(r.description)}\nmode: subagent\n---\n<!-- ${note} -->\n\n${r.body}`);
    write(path.join(out.agy, `${r.name}.md`),
      `---\nname: ${r.name}\ndescription: ${yamlStr(r.description)}\nmodel: inherit\n---\n<!-- ${note} -->\n\n${r.body}`);
  }

  // Skills: mirror .agents/skills into .claude/skills
  const src = path.join(ROOT, '.agents', 'skills'), dst = path.join(ROOT, '.claude', 'skills');
  fs.rmSync(dst, { recursive: true, force: true });
  const skills = fs.existsSync(src) ? fs.readdirSync(src).filter(d => fs.existsSync(path.join(src, d, 'SKILL.md'))) : [];
  for (const s of skills) fs.cpSync(path.join(src, s), path.join(dst, s), { recursive: true });

  return { roles: roles.map(r => r.name), skills };
}

helpIfAsked(isMain(import.meta.url) ? import.meta.url : null);
if (isMain(import.meta.url)) {
  const r = sync();
  console.log(`synced ${r.roles.length} roles (${r.roles.join(', ')}) and ${r.skills.length} skills for Claude Code, Codex, OpenCode and Antigravity`);
}
